const WRAPPED = [
  "   3.2  TRANSFER",
  "",
  "      The server MUST close the data connection when the client",
  "      requests it, and the client should send a final block first.",
].join("\n");

describe("floor extractors", () => {
  it("F1 keeps only modal-bearing sentences", () => {
    const rows = f1ModalSentences(WRAPPED, "punct");
    assert.equal(rows.length, 1);
    assert.match(rows[0].exact_text, /MUST close the data connection/);
  });

  it("F1 under the labeller's own boundary rule keeps the period, and under `dot` does not", () => {
    // This is the whole splitter-sensitivity finding in one assertion: the two rules find
    // the same sentence and the bytes differ, so a probe cut by one does not match the
    // other. Same three lines, 100% and 7%.
    const [punct] = f1ModalSentences("It may be sent. It must be sent.", "punct");
    const [dot] = f1ModalSentences("It may be sent. It must be sent.", "dot");
    assert.equal(punct.exact_text, "It may be sent.");
    assert.equal(dot.exact_text, "It may be sent");
    assert.notEqual(punct.exact_text, dot.exact_text);
  });

  it("F1 under `none` is the degenerate whole-section emitter", () => {
    const rows = f1ModalSentences(WRAPPED, "none");
    assert.equal(rows.length, 1);
    assert.ok(norm(WRAPPED).includes(rows[0].exact_text));
  });

  it("F2 emits one row per section carrying everything", () => {
    const rows = f2WholeSection(WRAPPED);
    assert.equal(rows.length, 1);
    assert.equal(rows[0].exact_text, norm(WRAPPED));
    assert.deepEqual(f2WholeSection("   "), []);
  });

  it("F3 emits whole blocks that carry a modal, unsplit", () => {
    const rows = f3ModalBlocks([
      { id: "b1", kind: "paragraph", text: "The host MUST drop the datagram." },
      { id: "b2", kind: "paragraph", text: "There are two cases." },
      { id: "b3", kind: "table", text: "Field | Value | MUST be 0" },
    ]);
    assert.deepEqual(
      rows.map((r) => r.block_id),
      ["b1", "b3"],
    );
    assert.match(rows[0].exact_text, /MUST drop the datagram\.$/);
  });

  it("the three extractors are in increasing triviality and the row counts go the other way", () => {
    const sections = [{ section: "3.2", text: WRAPPED, blocks: [{ id: "b1", kind: "paragraph", text: WRAPPED }] }];
    const rows = floorRows(sections);
    assert.deepEqual([...rows.keys()], ["F1_modal_sentence", "F3_modal_block", "F2_whole_section"]);
    // F2 is the most trivial extractor and the smallest, which is the point: a whole-section
    // emitter is one row per section, and the old matcher scored it 100%.
    assert.equal(rows.get("F1_modal_sentence").length, 1);
    assert.equal(rows.get("F3_modal_block").length, 1);
    assert.equal(rows.get("F2_whole_section").length, 1);
    assert.deepEqual([...splitterSensitivityRows(sections).map((s) => s.splitter)], Object.keys(SPLITTERS));
  });
});

describe("matcher", () => {
  const probe = "The host MUST drop the datagram.";

  it("a row equal to the probe matches at any margin", () => {
    assert.deepEqual(statementMatch(probe, probe, MATCH_MARGIN).hit, true);
  });

  it("a row that merely contains the probe is a hit at 1.0 and a miss once the probe is half again shorter", () => {
    const row = `${probe} The host SHOULD log the drop for later diagnosis.`;
    const loose = statementMatch(row, probe, MATCH_MARGIN);
    assert.equal(loose.contains, true);
    assert.equal(loose.hit, false);
    assert.ok(loose.ratio > MATCH_MARGIN);
    assert.equal(statementMatch(row, probe, Infinity).hit, true);
    assert.equal(statementMatch(row, probe, 1).hit, false);
  });

  it("findBounded reports what the bound excluded instead of dropping it", () => {
    const items = [{ exact_text: probe }, { exact_text: `${probe} And a second sentence about logging.` }];
    const m = findBounded(items, probe, MATCH_MARGIN);
    assert.equal(m.hits.length, 1);
    assert.equal(m.excluded.length, 1);
    assert.ok(m.excluded[0].ratio > MATCH_MARGIN);
    assert.equal(findUnbounded(items, probe).hits.length, 2);
  });

  it("a whole-section row is a containment hit and a bounded miss", () => {
    // The two figures the red team published, reproducible from these two calls.
    const section = `Introduction. ${probe} The port number is chosen by the server. Acknowledgements.`;
    assert.equal(findUnbounded([{ exact_text: section }], probe).hits.length, 1);
    assert.equal(findBounded([{ exact_text: section }], probe, MATCH_MARGIN).hits.length, 0);
  });

  it("the margin sweep runs from exact length to unbounded", () => {
    assert.equal(MARGIN_SWEEP[0], 1);
    assert.equal(MARGIN_SWEEP[MARGIN_SWEEP.length - 1], Infinity);
  });

  it("byte-exact containment is the control and it is stricter than normalisation", () => {
    const wrapped = "The host\n      MUST drop the datagram.";
    assert.equal(findExact([{ exact_text: wrapped }], probe).hits.length, 0);
    assert.equal(findBounded([{ exact_text: wrapped }], probe, MATCH_MARGIN).hits.length, 1);
  });

  it("quantiles handles an empty population without inventing a number", () => {
    assert.equal(quantiles([]), null);
    assert.deepEqual(quantiles([1, 1, 3.146]), { min: 1, q25: 1, median: 1, q75: 3.146, max: 3.146 });
  });
});

describe("negative probes", () => {
  const gen = (className, name) =>
    NEGATIVE_CLASSES.flatMap((c) => (c.class === className ? c.generators.filter((g) => g.name === name) : [])).at(0);

  it("quoted_keyword catches the RFC 2119 boilerplate and not a real obligation", () => {
    const test = gen("meta_language", "quoted_keyword").test;
    assert.equal(
      test(
        'The key words "MUST", "MUST NOT", "REQUIRED", "SHALL" in this document are to be interpreted as described in RFC 2119.',
      ),
      true,
    );
    assert.equal(test("The host MUST drop the datagram and log the drop."), false);
  });

  it("about_the_language catches a definitional sentence and not one that merely names the RFC", () => {
    const test = gen("meta_language", "about_the_language").test;
    assert.equal(
      test("The key words in this document are to be interpreted as described in RFC 2119 and RFC 8174."),
      true,
    );
    assert.equal(
      test("The words used above are to be interpreted as having the meanings given in this section."),
      true,
    );
    // The false label this mechanism must never produce: a real obligation that cites the RFC.
    assert.equal(test("A host MUST NOT violate the requirements stated in RFC 2119."), false);
  });

  it("relative_clause_modal catches a modal inside a relative clause", () => {
    const test = gen("descriptive_modal", "relative_clause_modal").test;
    assert.equal(test("Parameters which may be in place are ignored by the receiver."), true);
    assert.equal(test("The receiver MUST ignore every parameter it does not recognise."), false);
  });

  it("descriptive_modal is gated off any sentence carrying an upper-case keyword", () => {
    const cls = NEGATIVE_CLASSES.find((c) => c.class === "descriptive_modal");
    assert.equal(cls.gate("A sender MUST close the connection which may be idle."), false);
    assert.equal(cls.gate("A sender should close the connection which may be idle."), true);
  });

  it("no_modal_token fires on a sentence with no modal and not on one that has", () => {
    const test = gen("no_modal", "no_modal_token").test;
    assert.equal(test("The default port for the service is 25 for mail transfer."), true);
    assert.equal(test("A host must listen on the port or the connection is refused."), false);
  });

  it("preformatted is a separate, contested class rather than folded into the must-not set", () => {
    const cls = NEGATIVE_CLASSES.find((c) => c.class === "preformatted_block");
    assert.equal(cls.contested, true);
    assert.deepEqual(cls.kinds, ["preformatted"]);
    assert.ok(!NEGATIVE_CLASSES.some((c) => c.class === "nonprose_block" && c.kinds.includes("preformatted")));
  });

  it("a probe that is also a golden probe is dropped and counted as a collision", () => {
    const sections = [
      {
        rfc: 2119,
        section: "1",
        text: 'The key words "MUST", "MUST NOT", "REQUIRED", "SHALL", "SHOULD" in this document are to be interpreted as described in RFC 2119.',
        blocks: [],
      },
    ];
    const { probes, collisions } = negativeProbes(sections, { strictProbes: new Set([norm(sections[0].text)]) });
    assert.equal(probes.length, 0);
    assert.equal(collisions.length, 1);
    assert.equal(collisions[0].class, "meta_language");
  });

  it("a non-prose class only reads the blocks of its own kinds", () => {
    const sections = [
      {
        rfc: 2822,
        section: "3",
        text: "ignored, the class reads blocks",
        blocks: [
          { id: "b1", kind: "paragraph", text: "A host MUST drop the datagram and log the drop for diagnosis." },
          { id: "b2", kind: "table", text: "Resent-From: | MUST be present when the flag is set." },
        ],
      },
    ];
    const { probes } = negativeProbes(sections, {});
    const nonprose = probes.filter((p) => p.class === "nonprose_block");
    assert.deepEqual(
      nonprose.map((p) => p.block_id ?? p.block_kind),
      ["table"],
    );
    assert.equal(negativeCensus(probes)["nonprose_block/keyword_in_non_prose_block"], 1);
  });
});

describe("conservation", () => {
  const TABLE_SECTION = {
    rfc: 959,
    section: "3.2",
    text: "The server MUST close the data connection when the transfer is complete. The following field MUST be present in every message sent after a transfer: Resent-From: | MUST be present when the flag is set.",
    blocks: [
      { id: "b1", kind: "paragraph", text: "The server MUST close the data connection when the transfer is complete." },
      { id: "b2", kind: "table", text: "Resent-From: | MUST be present when the flag is set." },
    ],
  };

  it("R1 splits 'cover' into four arms, and only the first one is coverage", () => {
    // The four arms, and the reason Y5-as-worded is false: it scored the last three the
    // same, so a section full of bibliography entries satisfied it.
    const sections = [
      {
        rfc: 1,
        section: "1",
        text: [
          "A host MUST log the drop.",
          "The operator may log the drop to a file.",
          "A host should copy the log to an archive.",
          "A host may copy the log to an archive.",
          "A host logs the drop to disk for later analysis by the operator.",
        ].join(" "),
        blocks: [],
      },
    ];
    const channels = {
      requirements: [{ exact_text: "A host MUST log the drop.", section: "1" }],
      candidates: [{ exact_text: "The operator may log the drop to a file.", section: "1" }],
      fragments: [{ exact_text: "A host should copy the log to an archive.", section: "1" }],
      mentions: [{ exact_text: "A host may copy the log to an archive.", section: "1" }],
    };
    const pooled = poolReach(sectionReach(sections, channels));
    // The fifth sentence carries no keyword and is not in the population at all.
    assert.equal(pooled.keyword_bearing_sentences, 4);
    assert.deepEqual(pooled.arms, { requirement: 1, candidate: 1, fragment: 1, mention: 1, unreached: 0 });
    // Four reaches, one of which is a requirement. `any_reach` is 100% and `coverage` is
    // 25%: the two numbers are different numbers and conflating them is the falsified law.
    assert.equal(pooled.any_reach_pct, 100);
    assert.equal(pooled.coverage_pct, 25);
  });

  it("R1 will not credit a row that carries the sentence from a DIFFERENT section", () => {
    // The audit's G0189 shape: a probe in section 12 satisfied by rows in sections 7, 8, 9
    // and 14. Attribution is part of the reach, not an afterthought.
    const sections = [
      { rfc: 8447, section: "12", text: "IESG Approval is REQUIRED for a Y->N transition.", blocks: [] },
    ];
    const wrong = poolReach(
      sectionReach(sections, {
        requirements: [{ exact_text: "IESG Approval is REQUIRED for a Y->N transition.", section: "7" }],
      }),
    );
    assert.equal(wrong.arms.unreached, 1);
    const right = poolReach(
      sectionReach(sections, {
        requirements: [{ exact_text: "IESG Approval is REQUIRED for a Y->N transition.", section: "12" }],
      }),
    );
    assert.equal(right.arms.requirement, 1);
  });

  it("R1 splits the unreached three ways, and the text-view-only bucket is not prose", () => {
    // The text view flattens: the table row arrives inside a sentence longer than the block,
    // so the attribution has to run in both directions or this reads as a parser
    // disagreement when the real answer is "the tool declined to scan a table".
    const per = sectionReach([TABLE_SECTION], { requirements: [], candidates: [], fragments: [], mentions: [] });
    const pooled = poolReach(per);
    assert.equal(pooled.keyword_bearing_sentences, 2);
    assert.equal(pooled.unreached, 2);
    // One of the two sits in the table block - a decision the tool states - and the other in
    // the paragraph block, with nothing in the response to explain it. That is the split.
    assert.equal(pooled.unreached_by_block_kind.table, 1);
    assert.equal(pooled.unreached_by_block_kind.paragraph, 1);
    assert.equal(pooled.undeclared.count, 1);

    const noBlock = poolReach(
      sectionReach(
        [
          {
            rfc: 1122,
            section: "3.3.3",
            text: "A host must be able to accept a datagram on any port and drop it.",
            blocks: [],
          },
        ],
        {
          requirements: [],
          candidates: [],
          fragments: [],
          mentions: [],
        },
      ),
    );
    assert.equal(noBlock.text_view_only.count, 1);
    assert.equal(noBlock.undeclared.count, 0);
  });

  it("R1 imports no length floor from the positive set: 'It is a MUST.' counts", () => {
    const pooled = poolReach(
      sectionReach(
        [
          {
            rfc: 1,
            section: "1",
            text: "It is a MUST.",
            blocks: [{ id: "b", kind: "paragraph", text: "It is a MUST." }],
          },
        ],
        {
          requirements: [],
          candidates: [],
          fragments: [],
          mentions: [],
        },
      ),
    );
    assert.equal(pooled.keyword_bearing_sentences, 1);
    assert.equal(pooled.undeclared.count, 1);
    assert.equal(pooled.undeclared.under_45_chars, 1);
  });

  it("R2 catches a row that states the opposite of the sentence it quotes, at the primary keyword", () => {
    // The failure a coverage law is passed by: the reach is perfect, the obligation is
    // inverted. The check reads the keyword at the row's OWN offset, because a sentence
    // routinely holds two keywords of opposite polarity and judging the whole sentence
    // flags every one of those.
    const row = (text, polarity, kwTerm, kwOffset) => ({
      rfc: 1,
      section: "1",
      term: kwTerm,
      polarity,
      exact_text: text,
      span: { char_start: 1000 },
      keywords: [{ term: kwTerm, char_start: 1000 + kwOffset, char_end: 1000 + kwOffset + kwTerm.length }],
    });
    const rows = [
      row("A host MUST NOT send the datagram.", "positive", "MUST", 7),
      row("A host\n   MUST not reuse a connection.", "positive", "MUST", 7),
      row("A host MUST NOT send the datagram.", "negative", "MUST", 7),
      row("A host\n      MUST close the connection.", "absolute", "MUST", 7),
      // The keyword string is the whole negative phrase, which is how RFC 1122 and 1123
      // record it: judging the text after a keyword that already says NOT would report an
      // inverted obligation that is not inverted.
      row("An Internet system MUST NOT send 802 packets.", "negative", "MUST NOT", 21),
      // Two keywords, opposite polarity, and the row is about the FIRST clause.
      row("A User Agent MUST accept every format, and MUST NOT generate illegal syntax.", "positive", "MUST", 13),
    ];
    const f = fidelity(rows);
    assert.equal(f.rows_checked, 6);
    assert.equal(f.rows_read_at_their_own_offset, 6);
    assert.equal(f.rows_read_by_fallback_search, 0);
    assert.equal(f.disagreements, 2);
    assert.equal(f.agreement_pct, 66.7);
    assert.match(f.detail[0].why, /states the opposite/);
  });

  it("R2 counts a row it cannot read at an offset instead of guessing", () => {
    const f = fidelity([
      {
        rfc: 1,
        term: "MUST",
        polarity: "positive",
        exact_text: "A host MUST NOT reuse.",
        span: { char_start: 9999 },
        keywords: [{ term: "MUST", char_start: 5, char_end: 9 }],
      },
    ]);
    assert.equal(f.rows_read_by_fallback_search, 1);
    assert.equal(f.disagreements, 1);
  });

  it("R2 counts MAY NOT and NOT REQUIRED as vocabulary it does not judge", () => {
    // `MAY NOT` is not in NORMATIVE_TERMS; widening the vocabulary is a change to the
    // tool, and a checker that borrows the tool's own decision is not a checker.
    const row = (text, polarity, term, off) => ({
      rfc: 1,
      term,
      polarity,
      exact_text: text,
      span: { char_start: 0 },
      keywords: [{ term, char_start: off, char_end: off + term.length }],
    });
    const f = fidelity([
      row("A sender MAY NOT reuse the connection.", "positive", "MAY", 10),
      row("A host is NOT REQUIRED to answer.", "positive", "REQUIRED", 12),
    ]);
    assert.equal(f.vocabulary_out.may_not, 1);
    assert.equal(f.vocabulary_out.not_required, 1);
    assert.equal(f.vocabulary_out.asserted_positive, 1);
  });

  it("R3 names the channel that re-ships and the one that does not report its size", () => {
    const b = budgetConservation([
      {
        rfc: 3261,
        pages: 3,
        re_shipped_channels: ["non_strict_candidates.candidates"],
        channels_without_a_total: ["mentions"],
      },
      { rfc: 1812, pages: 3, re_shipped_channels: [], channels_without_a_total: ["mentions"] },
    ]);
    assert.equal(b.documents_re_shipping_a_channel, 1);
    assert.deepEqual(b.re_ship_detail[0], [3261, 3, ["non_strict_candidates.candidates"]]);
    assert.equal(b.documents_with_a_channel_that_does_not_report_its_size, 2);
    assert.match(b.not_checked, /not measurable from here/);
  });
});

describe("verify scenarios", () => {
  it("a corrupted id differs in one character and is still a well-formed id", () => {
    const id = "cit_9ed255775ae5527af92169fc";
    const bad = corruptId(id);
    assert.equal(bad.length, id.length);
    assert.match(bad, /^cit_[0-9a-f]{24}$/);
    assert.equal(bad.slice(0, -1), id.slice(0, -1));
  });

  it("quoteHash is the `sha256:`-prefixed hex of the exact text, as src/analysis/citation.ts computes it", async () => {
    assert.equal(
      quoteHash("x"),
      `sha256:${(await import("node:crypto")).createHash("sha256").update("x", "utf8").digest("hex")}`,
    );
  });

  it("every scenario names the verdict it requires and the ones it forbids", () => {
    for (const s of VERIFY_SCENARIOS) {
      assert.ok(s.contract, `${s.key} has no contract`);
      assert.ok(s.why.length > 40, `${s.key} has no stated reason`);
      if (s.key !== "S1_same_derivation") assert.ok(s.forbid.includes("verified"), `${s.key} does not forbid verified`);
    }
  });
});

describe("provenance", () => {
  it("normalisationMap round-trips: the normalised text is norm() and every index maps back", () => {
    const { normalised, map } = normalisationMap(WRAPPED);
    assert.equal(normalised, norm(WRAPPED));
    assert.equal(normalised.length, map.length);
    for (let i = 0; i < normalised.length; i += 1) {
      if (normalised[i] === " ") assert.ok(WRAPPED[map[i]].trim() === "", "a collapsed space must map to whitespace");
      else assert.equal(WRAPPED[map[i]], normalised[i]);
    }
  });

  it("locate finds a probe cut out of wrapped text and reports the raw span", () => {
    const probe = "The server MUST close the data connection when the client requests it";
    const at = locate(WRAPPED, probe);
    assert.ok(at);
    assert.equal(WRAPPED.slice(at.raw_start, at.raw_end).replace(/\s+/gu, " "), probe);
    assert.equal(normalisationMap(WRAPPED).normalised.slice(at.norm_start, at.norm_end), probe);
    assert.equal(at.occurrences, 1);
  });

  it("locate returns null for a probe that is not in the text, which is the answer a post-resync rebuild needs", () => {
    assert.equal(locate(WRAPPED, "A sentence that was never written in this section at all."), null);
    assert.equal(locate(WRAPPED, ""), null);
  });

  it("a sentence that occurs twice in a section is reported as two, not silently picked", () => {
    const twice = `${WRAPPED}\n${WRAPPED}`;
    assert.equal(locate(twice, "The server MUST close the data connection when the client requests it").occurrences, 2);
  });
});
