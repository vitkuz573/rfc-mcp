// Tests for the instrument's own instruments.
//
//   node --test eval/lib/instruments.test.mjs
//
// These are not tests of the tool. They are tests of the things that decide what the
// bench's numbers MEAN, and they are here because each one of them was, at some point in
// this project's history, a claim rather than a computation:
//
//   floor      - a 3-line grep scored 100% on the positive set. If the floor extractors
//                stop emitting what they claim to emit, the VOID rule silently stops firing
//                and every headline number becomes a measurement of nothing.
//   match      - the bound is the difference between "the row is a statement containing the
//                probe" and "the row contains the probe somewhere". A change in the bound
//                that nobody notices is how a floor extractor comes back to life.
//   negative   - the negative set is generated by regexes, and a regex that stops firing
//                empties a class without any error. Each generator is pinned to a sentence
//                it must catch and a sentence it must not catch.
//   conservation - the invisible-sentence split is three buckets and the "no stated reason"
//                bucket is the one that means something is wrong. Losing the distinction
//                between "in a table" and "in no block at all" would merge a documented
//                decision with a parser disagreement.
//   labelling  - `locate` is what makes a stale golden rule detectable instead of silent,
//                and it maps between two views of the same text, which is exactly the kind
//                of function that is right for the samples and wrong for the cases.

import assert from "node:assert/strict";
import { describe, it } from "node:test";

